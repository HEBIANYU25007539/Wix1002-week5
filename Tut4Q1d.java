public class Tut4Q1d {
    public static void main(String[] args) {
        int givenNumber = 10;
        int sum = 0;
        for (int i = 1; i <= givenNumber; i++) {
            sum += i;
        }
        System.out.println("Sum from 1 to " + givenNumber + ": " + sum);
    }
}
